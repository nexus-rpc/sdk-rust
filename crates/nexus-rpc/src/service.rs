use std::marker::PhantomData;

/// A Nexus operation input that can cross an integration boundary.
pub trait NexusInput: Send + 'static {}

impl<T> NexusInput for T where T: Send + 'static {}

/// A Nexus operation output that can cross an integration boundary.
pub trait NexusOutput: Send + 'static {}

impl<T> NexusOutput for T where T: Send + 'static {}

/// A generated zero-sized type that identifies a Nexus service.
pub trait NexusService: 'static {
    /// Returns the Nexus wire name for this service.
    fn name() -> &'static str;
}

/// Immutable metadata supplied by generated Nexus service definitions.
pub trait NexusServiceMetadata: NexusService {
    /// Returns immutable metadata for the declared operations.
    fn definition() -> &'static ServiceDefinition;
}

/// A generated zero-sized type that identifies one operation on a Nexus service.
pub trait NexusOperation: 'static {
    /// Service that declares this operation.
    type Service: NexusService;
    /// Operation input type.
    type Input: NexusInput;
    /// Operation output type.
    type Output: NexusOutput;

    /// Returns the Nexus wire name for this operation.
    fn name(&self) -> &str;
}

/// Generated immutable operation metadata stored by a service definition.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct OperationDefinitionInfo {
    rust_name: &'static str,
    wire_name: &'static str,
    input_type_name: &'static str,
    output_type_name: &'static str,
}

impl OperationDefinitionInfo {
    pub(crate) const fn new(
        rust_name: &'static str,
        wire_name: &'static str,
        input_type_name: &'static str,
        output_type_name: &'static str,
    ) -> Self {
        Self {
            rust_name,
            wire_name,
            input_type_name,
            output_type_name,
        }
    }

    /// Returns the Rust method name in the service declaration.
    pub const fn rust_name(&self) -> &'static str {
        self.rust_name
    }

    /// Returns the Nexus wire name for the operation.
    pub const fn wire_name(&self) -> &'static str {
        self.wire_name
    }

    /// Returns the diagnostic Rust type name of the operation input.
    pub const fn input_type_name(&self) -> &'static str {
        self.input_type_name
    }

    /// Returns the diagnostic Rust type name of the operation output.
    pub const fn output_type_name(&self) -> &'static str {
        self.output_type_name
    }
}

/// Immutable service metadata generated by [`crate::nexus_service`].
#[derive(Debug)]
pub struct ServiceDefinition {
    name: &'static str,
    operations: &'static [OperationDefinitionInfo],
}

impl ServiceDefinition {
    pub(crate) const fn new(
        name: &'static str,
        operations: &'static [OperationDefinitionInfo],
    ) -> Self {
        Self { name, operations }
    }

    /// Returns the Nexus service wire name.
    pub const fn name(&self) -> &'static str {
        self.name
    }

    /// Returns the immutable erased operation metadata slice.
    pub const fn operations(&self) -> &'static [OperationDefinitionInfo] {
        self.operations
    }
}

/// Typed operation metadata generated by [`crate::nexus_service`].
#[derive(Debug)]
pub struct OperationDefinition<I, O> {
    info: &'static OperationDefinitionInfo,
    _marker: PhantomData<fn(I) -> O>,
}

impl<I, O> OperationDefinition<I, O> {
    pub(crate) const fn new(info: &'static OperationDefinitionInfo) -> Self {
        Self {
            info,
            _marker: PhantomData,
        }
    }

    /// Returns the shared erased operation metadata.
    pub const fn info(&self) -> &'static OperationDefinitionInfo {
        self.info
    }
}
